val IdleFleetShapes = Shapes(
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(22.dp),
    extraLarge = RoundedCornerShape(28.dp),
)

object IdleFleetTheme {
    val statusColors: FleetStatusColors
        @Composable
        @ReadOnlyComposable
        get() = LocalFleetStatusColors.current
}

@Composable
fun IdleFleetTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val statusColors = if (darkTheme) DarkFleetStatusColors else LightFleetStatusColors

    CompositionLocalProvider(LocalFleetStatusColors provides statusColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = IdleFleetTypography,
            shapes = IdleFleetShapes,
            content = content,
        )
    }
}
